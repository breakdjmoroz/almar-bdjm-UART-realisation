`timescale 1ns/100ps
module array_literals ();

byte a [0:1][0:2];

initial begin
    // Инициализация поэлементно (обход ограничения Icarus)
    // Первая строка (индекс 0)
    a[0][0] = 0;
    a[0][1] = 1;
    a[0][2] = 2;
    
    // Вторая строка (индекс 1), заполняем значением 8'h9 (это число 9)
    a[1][0] = 8'h9;
    a[1][1] = 8'h9;
    a[1][2] = 8'h9;

    $display ("a[0][0] =%d", a[0][0]);
    $display ("a[0][1] =%d", a[0][1]);
    $display ("a[0][2] =%d", a[0][2]);
    $display ("a[1][0] =%d", a[1][0]);
    $display ("a[1][1] =%d", a[1][1]);
    $display ("a[1][2] =%d", a[1][2]);
    
    #1 $finish;
end

endmodule